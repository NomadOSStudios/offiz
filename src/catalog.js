export const MIN_SIZE = 0.1;

// The catalog entry with any per-item size overrides applied. Builders read
// w/d/h from this, so a resized item is just rebuilt with different numbers.
export function itemDef(def, data) {
  const pick = (k) =>
    Number.isFinite(data[k]) ? Math.max(MIN_SIZE, data[k]) : def[k];
  return { ...def, w: pick("w"), d: pick("d"), h: pick("h") };
}

export function sizeLabel(def) {
  const cm = (v) => Math.round(v * 100);
  return `${cm(def.w)} × ${cm(def.d)} × ${cm(def.h)} cm`;
}

export function buildItem(def, color) {
  // Very small custom sizes retain valid fabrication proportions before fitting
  // to their requested envelope. No mesh may spill outside placement bounds.
  const working = {
    ...def,
    w: Math.max(0.4, def.w),
    d: Math.max(0.3, def.d),
    h: Math.max(0.35, def.h),
  };
  // Thin desktop and wall objects are intentionally built at their real depth.
  if (
    def.stackable ||
    def.wallMounted ||
    def.passable ||
    def.type === "partition"
  ) {
    working.d = def.d;
    working.h = def.h;
  }
  const g = def.build(working, color || def.color);
  const bounds = new THREE.Box3().setFromObject(g);
  const size = bounds.getSize(new THREE.Vector3());
  const center = bounds.getCenter(new THREE.Vector3());
  const scale = new THREE.Vector3(
    Math.min(1, def.w / size.x),
    Math.min(1, def.h / size.y),
    Math.min(1, def.d / size.z),
  );
  // Bake fitting into geometry so editor transforms remain simple and reusable.
  g.traverse((o) => {
    if (o.isMesh) {
      o.geometry.translate(-center.x, -bounds.min.y, -center.z);
      o.geometry.scale(scale.x, scale.y, scale.z);
      o.geometry.computeBoundingBox();
      o.geometry.computeBoundingSphere();
    } else if (o.isLight) {
      o.position
        .sub(new THREE.Vector3(center.x, bounds.min.y, center.z))
        .multiply(scale);
    }
  });
  g.traverse((o) => {
    if (o.isMesh) o.userData.item = true;
  });
  return g;
}
